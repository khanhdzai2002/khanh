"""Read-only report UI on synthetic serve-smoke _test + Vite5175 only."""
import csv,io,uuid
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(locale='vi-VN',viewport={'width':1440,'height':1000});page.set_default_timeout(10000)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://localhost:5175',wait_until='networkidle')
 page.get_by_role('button',name='Đăng nhập DEV (dữ liệu thử nghiệm)',exact=True).click()
 expect(page.get_by_text('MÔI TRƯỜNG PHÁT TRIỂN',exact=False)).to_be_visible()
 me=page.request.get('http://localhost:5175/api/me').json();assert me['development']
 headers={'Origin':'http://localhost:5175','X-CSRF-Token':me['csrf']}
 def post(path,body,extra=None):
  r=page.request.post('http://localhost:5175'+path,data=body,headers={**headers,**(extra or {})});assert r.ok,r.text();return r.json()
 def sku(code,color,size):return post('/api/skus',{'sku':code,'color':color,'size':size})['id']
 a=sku('SYNTH-A','Cam','M');a2=sku('SYNTH-A','Trắng','S');bb=sku('SYNTH-B','Đen','L')
 def order(items,supplier,status='Đã xác nhận'):
  return post('/api/orders',{'time':'2026-10-20T10:00:00+07:00','supplier':supplier,'delivery':'2026-10-20','requestedBy':'Synthetic report planner','notes':'Synthetic report only','status':status,'items':[{'variantId':i,'qty':q,'priority':'THƯỜNG'} for i,q in items]})
 first=order([(a,100),(bb,300)],'Synthetic factory One')
 second=order([(a2,200)],'Synthetic factory Two')
 post('/api/orders/'+second['id']+'/receipts',{'expectedVersion':second['version'],'date':'2026-10-21','note':'Synthetic partial','lines':[{'itemId':second['items'][0]['id'],'qty':50}]},{'Idempotency-Key':str(uuid.uuid4())})
 order([(a,999)],'Synthetic draft','Nháp')
 page.get_by_role('button',name='Tải lại dữ liệu',exact=True).click()
 page.get_by_role('button',name='Gối lệnh sản xuất',exact=True).click()
 page.get_by_role('button',name='Báo cáo tỷ trọng sản phẩm',exact=True).click()
 report=page.locator('.production-report')
 expect(report.get_by_role('heading',name='Báo cáo tỷ trọng sản phẩm gối',exact=True)).to_be_visible()
 expect(report.locator('.production-report-kpis')).to_contain_text('550')
 card=report.locator('.production-product').filter(has=page.locator('.production-product-heading strong',has_text='SYNTH-A'))
 expect(card.locator('.production-product-heading')).to_contain_text('250 sp · 45,5%')
 card.locator('.production-product-heading').click()
 matrix=report.get_by_role('table',name='Màu và size SYNTH-A',exact=True)
 expect(matrix.locator('tfoot')).to_contain_text('250')
 sources=report.get_by_role('table',name='Lệnh của SYNTH-A',exact=True)
 expect(sources).to_contain_text('25%');expect(sources).to_contain_text('100%')
 sources.get_by_role('button',name=first['code'],exact=True).click()
 dialog=page.get_by_role('dialog');expect(dialog).to_contain_text(first['code']);dialog.get_by_role('button',name='Đóng',exact=True).click()
 report.get_by_label('Mã sản phẩm báo cáo',exact=True).select_option('SYNTH-A')
 expect(card.locator('.production-product-heading')).to_contain_text('250 sp · 100%')
 expect(sources).to_contain_text('25%')
 report.get_by_label('Tỷ trọng theo số lượng',exact=True).select_option('placed')
 expect(card.locator('.production-product-heading')).to_contain_text('300 sp · 100%')
 expect(matrix.locator('tfoot')).to_contain_text('300')
 with page.expect_download() as export:report.get_by_role('link',name='Xuất báo cáo CSV',exact=True).click()
 rows=list(csv.reader(io.StringIO(Path(export.value.path()).read_text(encoding='utf-8-sig'))))
 assert len(rows)==3 and sum(int(r[8]) for r in rows[1:])==300 and all(r[0]=='SYNTH-A' for r in rows[1:])
 report.get_by_label('Nhà xưởng báo cáo',exact=True).select_option('Synthetic factory One')
 expect(card.locator('.production-product-heading')).to_contain_text('100 sp · 100%')
 report.get_by_label('Từ ngày lập lệnh',exact=True).fill('2026-10-22');report.get_by_label('Đến ngày lập lệnh',exact=True).fill('2026-10-20')
 expect(report.get_by_text('Ngày bắt đầu phải trước hoặc bằng ngày kết thúc.',exact=True)).to_be_visible()
 assert report.get_by_role('link',name='Xuất báo cáo CSV',exact=True).count()==0
 report.get_by_role('button',name='Đặt lại bộ lọc',exact=True).click()
 expect(report.locator('.production-report-kpis')).to_contain_text('550')
 report.get_by_label('Tính cả nháp',exact=False).check()
 expect(report.locator('.production-report-kpis')).to_contain_text('1.549')
 report.get_by_label('Tính cả nháp',exact=False).uncheck()
 report.get_by_label('Lệnh sản xuất báo cáo',exact=True).select_option(first['id'])
 report.get_by_label('Tỷ trọng theo số lượng',exact=True).select_option('placed')
 expect(card.locator('.production-product-heading')).to_contain_text('100 sp · 25%')
 report.get_by_role('button',name='Đặt lại bộ lọc',exact=True).click()
 page.screenshot(path='/tmp/comsflow-production-report-desktop.png',full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 expect(page.locator('aside')).to_have_css('transform','matrix(1, 0, 0, 1, -250, 0)')
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
 page.screenshot(path='/tmp/comsflow-production-report-mobile.png',full_page=True)
 assert not errors,errors
 print('PASS report UI: product shares/colour-size totals -> order detail -> product and supplier filters -> placed vs pending -> filtered CSV -> invalid dates -> explicit draft inclusion -> desktop/390px without JS errors. Synthetic only.')
 b.close()
